"""core — Shared architectural primitives & typed contracts for Agent-first-browse.

Provides lightweight, zero-dependency foundations shared across the browser engine,
evaluation connector, and orchestration layers:
  - `core.errors`: Typed domain exception hierarchy with stable `ErrorCode` values,
    explicit `.retryable` metadata, and JSON-safe serialization.
  - `core.retries`: Eagerly-validated full-jitter exponential backoff & async `try_n`.
  - `core.url_policy`: Defense-in-depth URL & RFC 6890 SSRF validator.
  - `core.truncate`: Structural water-filling JSON & text payload truncation.
  - `core.redaction`: Cycle-/depth-bounded base64, screenshot, & secret redaction.
  - `core.disposable`: LIFO sync/async disposable stores & listener-isolated `Emitter`.
  - `core.runtime_context`: `ContextVar`-backed per-session DI runtime context.
  - `core.browser_provider`: `BrowserProvider` seam, per-session locks, & restart tombstones.
  - `core.observability`: Schema-versioned typed event bus & pluggable telemetry sinks.
"""

